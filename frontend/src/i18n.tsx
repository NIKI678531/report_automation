const messages = {
  ...baseMessages,
  "zh-Hant": zhHantMessages,
};

type MessageKey = keyof typeof messages.en;
type Params = Record<string, string | number>;

function interpolate(value: string, params: Params = {}): string {
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

interface LocaleContextValue {
  locale: Locale;
  languageMode: ReportLanguage;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, params?: Params) => string;
  formatDate: (value: string) => string;
  formatMonth: (value: string) => string;
  statusLabel: (value: string) => string;
}

const fallback: LocaleContextValue = {
  locale: "en",
  languageMode: "EN",
  setLocale: () => undefined,
  t: (key, params) => interpolate(messages.en[key], params),
  formatDate: (value) => new Intl.DateTimeFormat("en-GB", {
    year: "numeric", month: "long", day: "numeric", timeZone: "UTC",
  }).format(new Date(`${value.slice(0, 10)}T00:00:00Z`)),
  formatMonth: (value) => new Intl.DateTimeFormat("en-HK", {
    year: "numeric", month: "long", timeZone: "UTC",
  }).format(new Date(`${value.slice(0, 7)}-01T00:00:00Z`)),
  statusLabel: (value) => value,
};

const LocaleContext = createContext<LocaleContextValue>(fallback);
const DocumentLanguageContext = createContext(true);

export function reportLocale(language: ReportLanguage | "BILINGUAL"): Locale {
  return language === "ZH_HANS" ? "zh-Hans" : language === "ZH_HANT" ? "zh-Hant" : "en";
}

export function LocaleProvider({ children, locale: controlledLocale, manageDocumentLanguage }: { children: ReactNode; locale?: Locale; manageDocumentLanguage?: boolean }) {
  const inheritedDocumentLanguage = useContext(DocumentLanguageContext);
  const updateDocumentLanguage = manageDocumentLanguage ?? inheritedDocumentLanguage;
  const [preferredLocale, setLocaleState] = useState<Locale>(() => (
    (["en", "zh-Hans", "zh-Hant"] as const).includes(
      window.localStorage.getItem("commentary.locale") as Locale,
    ) ? window.localStorage.getItem("commentary.locale") as Locale : "en"
  ));
  const locale = controlledLocale ?? preferredLocale;
  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    languageMode: locale === "zh-Hans" ? "ZH_HANS" : locale === "zh-Hant" ? "ZH_HANT" : "EN",
    setLocale: (next) => {
      if (controlledLocale !== undefined) return;
      window.localStorage.setItem("commentary.locale", next);
      setLocaleState(next);
    },
    t: (key, params) => interpolate(messages[locale][key], params),
    formatDate: (value) => new Intl.DateTimeFormat(locale === "zh-Hans" ? "zh-CN" : locale === "zh-Hant" ? "zh-HK" : "en-GB", {
      year: "numeric", month: "long", day: "numeric", timeZone: "UTC",
    }).format(new Date(`${value.slice(0, 10)}T00:00:00Z`)),
    formatMonth: (value) => new Intl.DateTimeFormat(locale === "zh-Hans" ? "zh-CN" : locale === "zh-Hant" ? "zh-HK" : "en-HK", {
      year: "numeric", month: "long", timeZone: "UTC",
    }).format(new Date(`${value.slice(0, 7)}-01T00:00:00Z`)),
    statusLabel: (status) => locale === "en" ? status : ((locale === "zh-Hant" ? {
      DRAFT: "草稿", DATA_READY: "數據就緒", EDITING: "編輯中", QA_BLOCKED: "需關注",
      READY_TO_FINALIZE: "可定稿", REVIEW: "審閱中", FINALIZED: "已定稿", ARCHIVED: "已封存",
      MISSING: "缺失", AVAILABLE: "可用", VALIDATED: "已驗證", NEEDS_MAPPING: "需要配對",
      REJECTED: "已拒絕", APPLIED: "已套用", OVERRIDDEN: "已替代", HIGH: "高", MEDIUM: "中", LOW: "低",
    } : {
      DRAFT: "草稿", DATA_READY: "数据就绪", EDITING: "编辑中", QA_BLOCKED: "需关注",
      READY_TO_FINALIZE: "可终稿化", REVIEW: "审核中", FINALIZED: "已终稿", ARCHIVED: "已归档",
      MISSING: "缺失", AVAILABLE: "可用", VALIDATED: "已验证", NEEDS_MAPPING: "需要映射",
      REJECTED: "已拒绝", APPLIED: "已应用", OVERRIDDEN: "已替代", HIGH: "高", MEDIUM: "中", LOW: "低",
    })[status] ?? status),
  }), [locale, controlledLocale]);
  useEffect(() => {
    if (!updateDocumentLanguage) return;
    const previous = document.documentElement.lang;
    document.documentElement.lang = locale === "zh-Hans" ? "zh-CN" : locale === "zh-Hant" ? "zh-HK" : "en";
    return () => { document.documentElement.lang = previous; };
  }, [locale, updateDocumentLanguage]);
  return <DocumentLanguageContext.Provider value={updateDocumentLanguage}><LocaleContext.Provider value={value}><div lang={locale} style={{ display: "contents" }}>{children}</div></LocaleContext.Provider></DocumentLanguageContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}
